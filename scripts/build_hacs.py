"""Build the self-contained HACS entry point from the canonical www sources."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ("styles.js", "ha-liquid-glass.js")


def build():
    chunks = ["// Generated by scripts/build_hacs.py. Edit the sources in www/.\n"]
    for name in SOURCES:
        chunks.append(f"\n// ---- {name} ----\n")
        chunks.append((ROOT / "www" / name).read_text(encoding="utf-8").rstrip() + "\n;")
    return "".join(chunks) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if dist is stale")
    args = parser.parse_args()
    target = ROOT / "dist/ha_animated_backgrounds.js"
    content = build()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("Run python scripts/build_hacs.py and commit dist/.")
        print("HACS bundle matches both sources.")
    else:
        target.parent.mkdir(exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
        print(target)
